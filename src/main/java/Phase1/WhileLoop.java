package Phase1;

public class WhileLoop {
    public static void main(String[] args) {
        int i = 1, j=5;
        while(i<=5){
            System.out.println(i);
            i++;
        }
        System.out.println("Done");

        while(j >0){
            System.out.println(j);
            j--;
        }
    }
}
